import { ACTIVE, ALL_ROLES, BASE_ROLES, COLORS, SCHEME_KEYS, kebab, library, varName } from './library';
import { buildThemeCss } from './css';
import { ACTIVE_GRADIENTS, GRADIENT_ANGLE, buildGradientCss, gradientId, onGradient } from './gradients';
import { ACTIVE_FILLS, labelOf } from './gfill';

/** Commented list of gradient fills (target -> gradient), selector-agnostic, for the CSS export. Empty when there are none. */
function assignmentsCss(): string {
  if (!ACTIVE_FILLS.length) return '';
  const rows = ACTIVE_FILLS.map((f) => {
    const g = ACTIVE_GRADIENTS.find((x) => x.id === f.grad);
    if (!g) return '';
    const bg = f.angle === GRADIENT_ANGLE ? `var(--antz-gradient-${g.id})` : `linear-gradient(${f.angle}deg, ${g.stops.map((x) => x.hex).join(', ')})`;
    return `/* ${labelOf(f)} */\n/* background: ${bg}; color: ${onGradient(g).hex}; */`;
  }).filter(Boolean);
  return `\n\n/* Gradient assignments (from the tester; apply to your own selectors) */\n${rows.join('\n')}`;
}

export interface ExportFile { name: string; mime: string; body: string }

/** Header line naming where the values came from: the library itself, or a theme generated from its key colours. */
function stamp() {
  if (ACTIVE.library) return `Generated by ANTZ Theme Tester from ANTZ_colour_library.json (seed ${library.seed}).`;
  const s = ACTIVE.sources;
  return `Generated by ANTZ Theme Tester: theme "${ACTIVE.name}" (${ACTIVE.style}) from the ANTZ key colours, primary ${s.primary}, secondary ${s.secondary}, tertiary ${s.tertiary}, neutral ${s.neutral}, neutral variant ${s.neutralVariant}. Error and extended colours are the library's.`;
}
/** File name with the theme id, so exports of different themes do not overwrite each other. */
const named = (base: string, ext: string) => (ACTIVE.library ? `${base}.${ext}` : `${base}-${ACTIVE.id}.${ext}`);

export function exportCss(): ExportFile {
  const css = `/* ${stamp()}\n   Six schemes. Set data-scheme on <html> (or any container) to one of:\n   ${SCHEME_KEYS.join(', ')}.\n   --md-sys-color-* / --md-extended-color-* aliases follow Material Theme Builder naming. */\n\n:root { color-scheme: light; }\n\n${buildThemeCss({ md: true }).replace('[data-scheme="light"]', ':root,\n[data-scheme="light"]')}\n\n/* The 5 ANTZ gradients for this theme (the same in every mode). */\n${buildGradientCss(ACTIVE_GRADIENTS)}${assignmentsCss()}\n`;
  return { name: named('antz-tokens', 'css'), mime: 'text/css', body: css };
}

export function exportTailwind(): ExportFile {
  const theme = ALL_ROLES.map((r) => `  --color-${kebab(r)}: var(${varName(r)});`).join('\n');
  const body = `/* ${stamp()}\n   Tailwind v4: import antz-tokens.css first, then this file.\n   Utilities like bg-primary-container / text-on-surface follow the active data-scheme.
   Gradients: use the CSS variables from antz-tokens.css, e.g. bg-(image:--antz-gradient-green-to-navy). */\n@import "tailwindcss";\n@import "./antz-tokens.css";\n\n@theme inline {\n${theme}\n}\n`;
  return { name: named('antz-tailwind', 'css'), mime: 'text/css', body };
}

export function exportJson(): ExportFile {
  const assignments = ACTIVE_FILLS.map((f) => ({ target: labelOf(f), scope: f.scope, gradient: ACTIVE_GRADIENTS.find((g) => g.id === f.grad)?.name ?? f.grad, angle: f.angle }));
  if (ACTIVE.library && !assignments.length) return { name: 'ANTZ_colour_library.json', mime: 'application/json', body: JSON.stringify(library, null, 2) };
  if (ACTIVE.library) return { name: 'ANTZ_colour_library.json', mime: 'application/json', body: JSON.stringify({ ...library, gradientAssignments: assignments }, null, 2) };
  // Same shape as the library; schemes are the generated ones, extended schemes and gradients unchanged.
  const schemes = Object.fromEntries(SCHEME_KEYS.map((k) => [k, Object.fromEntries(BASE_ROLES.map((r) => [r, COLORS[k][r]]))]));
  const out = {
    ...library,
    description: `${stamp()}\nPalettes and gradients below are the library's and were not regenerated for this theme.`,
    seed: ACTIVE.sources.primary,
    coreColors: { ...ACTIVE.sources, error: library.coreColors.error },
    schemes,
    gradients: ACTIVE_GRADIENTS.map((g) => ({ name: g.name, stops: g.stops.map((x) => ({ palette: x.palette, tone: x.tone, color: x.hex })) })),
    ...(assignments.length ? { gradientAssignments: assignments } : {}),
  };
  return { name: named('ANTZ_colour_library', 'json'), mime: 'application/json', body: JSON.stringify(out, null, 2) };
}

export function exportFlutter(): ExportFile {
  const toArgb = (h: string) => `Color(0xFF${h.slice(1).toUpperCase()})`;
  const camel = (k: string) => k.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
  const base = Object.keys(library.schemes.light);
  const schemes = SCHEME_KEYS.map((k) => {
    const brightness = k.startsWith('dark') ? 'Brightness.dark' : 'Brightness.light';
    const fields = base.map((r) => `    ${r}: ${toArgb(COLORS[k][r as keyof (typeof COLORS)[typeof k]])},`).join('\n');
    return `  static const ColorScheme ${camel(k)} = ColorScheme(\n    brightness: ${brightness},\n${fields}\n  );`;
  }).join('\n\n');
  const ext = SCHEME_KEYS.map((k) => {
    const e = library.extendedSchemes[k] as Record<string, Record<string, string>>;
    const rows = Object.entries(e).map(([name, v]) => `    '${name}': [${toArgb(v.color)}, ${toArgb(v.onColor)}, ${toArgb(v.colorContainer)}, ${toArgb(v.onColorContainer)}],`).join('\n');
    return `  static const Map<String, List<Color>> ${camel(k)}Extended = {\n${rows}\n  };`;
  }).join('\n\n');
  const camelG = (n: string) => gradientId(n).replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
  const rad = (GRADIENT_ANGLE * Math.PI) / 180;
  const grads = ACTIVE_GRADIENTS.map((g) => `  static const LinearGradient ${camelG(g.name)} = LinearGradient(\n    begin: Alignment(${(-Math.sin(rad)).toFixed(3)}, ${(Math.cos(rad)).toFixed(3)}), end: Alignment(${Math.sin(rad).toFixed(3)}, ${(-Math.cos(rad)).toFixed(3)}),\n    colors: [${g.stops.map((x) => toArgb(x.hex)).join(', ')}],\n  );`).join('\n');
  const body = `// ${stamp()}\n// Extended lists are [color, onColor, colorContainer, onColorContainer].\n// surfaceVariant / background are deprecated in recent Flutter; remove if your SDK warns.\nimport 'package:flutter/material.dart';\n\nclass AntzColorScheme {\n${schemes}\n\n${ext}\n}\n\n/// The 5 ANTZ gradients for this theme, ${GRADIENT_ANGLE}deg.\nclass AntzGradients {\n${grads}\n}\n`;
  return { name: named('antz_color_scheme', 'dart').replace(/-/g, '_'), mime: 'text/plain', body };
}

export function download(f: ExportFile) {
  const url = URL.createObjectURL(new Blob([f.body], { type: f.mime }));
  const a = document.createElement('a');
  a.href = url;
  a.download = f.name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
